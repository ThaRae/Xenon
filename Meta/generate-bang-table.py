#!/usr/bin/env python3

# Turns Xenon's !bangs (UI/Resources/bangs/bangs.json, from Meta/update-bangs.py) into the table UI/Bangs.cpp looks
# them up in. The build runs it (UI/Xenon.cmake).
#
# The table has one entry per trigger, sorted by trigger, so a lookup is a binary search. Every string lives in one
# array that the entries point into by offset, which keeps the table in read-only memory with no relocations for the
# loader to apply: the list costs nothing at startup, and only the pages a lookup touches are ever read in.

from __future__ import annotations

import argparse
import json

from pathlib import Path

# The bits of Bangs::Format, in Kagi's fmt names. Kagi turns every one on for a bang that has no fmt.
FORMAT_FLAGS = {
    "open_base_path": 1 << 0,
    "open_snap_domain": 1 << 1,
    "url_encode_placeholder": 1 << 2,
    "url_encode_space_to_plus": 1 << 3,
}


class Strings:
    def __init__(self):
        self.data = bytearray()
        self.offsets: dict[bytes, int] = {}

    def add(self, string: str) -> tuple[int, int]:
        encoded = string.encode()
        if encoded not in self.offsets:
            self.offsets[encoded] = len(self.data)
            self.data += encoded
        return self.offsets[encoded], len(encoded)


def c_string_literal(data: bytes) -> str:
    # NB: Octal escapes are at most three digits long, so unlike hex escapes they can't swallow the character after them.
    escaped = "".join(chr(byte) if 0x20 <= byte < 0x7F and byte not in b'"\\' else f"\\{byte:03o}" for byte in data)
    return f'"{escaped}"'


def main():
    parser = argparse.ArgumentParser(description="Generate Xenon's !bang lookup table")
    parser.add_argument("input", type=Path)
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args()

    strings = Strings()
    entries = []
    for bang in json.loads(args.input.read_text()):
        name = strings.add(bang["s"])
        query_url = strings.add(bang["u"])
        snap_domain = strings.add(bang.get("ad", ""))
        flags = sum(FORMAT_FLAGS[flag] for flag in bang.get("fmt", FORMAT_FLAGS))
        for trigger in (bang["t"], *bang.get("ts", [])):
            entries.append((trigger.encode(), strings.add(trigger), name, query_url, snap_domain, flags))
    entries.sort(key=lambda entry: entry[0])

    for (trigger, *_), (next_trigger, *_) in zip(entries, entries[1:]):
        if trigger == next_trigger:
            raise SystemExit(f"!{trigger.decode()} is in {args.input} twice")

    lines = [
        f"// Generated by Meta/generate-bang-table.py from {args.input.name}. Don't edit it; see Meta/update-bangs.py.",
        "",
        "#pragma once",
        "",
        "#include <AK/Array.h>",
        "#include <AK/Types.h>",
        "",
        "namespace Ladybird::Bangs::Table {",
        "",
        "// Offsets and lengths into strings.",
        "struct Entry {",
        "    u32 trigger_offset;",
        "    u32 name_offset;",
        "    u32 query_url_offset;",
        "    u32 snap_domain_offset;",
        "    u16 trigger_length;",
        "    u16 name_length;",
        "    u16 query_url_length;",
        "    u8 snap_domain_length;",
        "    u8 format;",
        "};",
        "",
        "static constexpr char strings[] =",
    ]
    lines += [f"    {c_string_literal(strings.data[start : start + 96])}" for start in range(0, len(strings.data), 96)]
    lines[-1] += ";"
    lines += ["", f"static constexpr Array<Entry, {len(entries)}> entries {{ {{"]
    for _, *fields, flags in entries:
        offsets = [offset for offset, _ in fields]
        lengths = [length for _, length in fields]
        if any(length > 0xFFFF for length in lengths) or lengths[-1] > 0xFF:
            raise SystemExit(f"a string in {args.input} is too long for the table")
        lines.append(f"    {{ {', '.join(map(str, offsets + lengths))}, {flags} }},")
    lines += ["} };", "", "}", ""]

    args.output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines)
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text)


if __name__ == "__main__":
    main()
